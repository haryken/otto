#!/usr/bin/env python3
"""Generate speak_embed.inc from boards/otto-robot/speak/."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SPEAK = os.path.join(HERE, "speak")
OUT = os.path.join(HERE, "speak_embed.inc")


def c_ident(filename):
    return re.sub(r"[^A-Za-z0-9]", "_", filename)


def mime_for(name):
    if name.endswith(".json"):
        return "application/json"
    if name.endswith(".jpg") or name.endswith(".jpeg"):
        return "image/jpeg"
    if name.endswith(".png"):
        return "image/png"
    return "application/octet-stream"


rows = []
for root, _, files in os.walk(SPEAK):
    for fn in sorted(files):
        if fn.startswith("."):
            continue
        # Firmware flash is too small to embed unit JPEGs; those come from LAN :8765.
        if fn.endswith(".jpg") or fn.endswith(".jpeg") or fn.endswith(".png"):
            continue
        full = os.path.join(root, fn)
        rel = os.path.relpath(full, HERE).replace("\\", "/")
        uri = "/" + rel
        ident = c_ident(fn)
        rows.append((uri, ident, mime_for(fn)))

rows.sort(key=lambda r: r[0])

lines = [
    "// Generated by gen_speak_embed.py — do not edit by hand.",
    "struct SpeakEmbedFile {",
    "    const char* uri;",
    "    const char* start;",
    "    const char* end;",
    "    const char* mime;",
    "};",
    "",
]
for uri, ident, mime in rows:
    lines.append(f'extern const char {ident}_start[] asm("_binary_{ident}_start");')
    lines.append(f'extern const char {ident}_end[] asm("_binary_{ident}_end");')
lines.append("")
lines.append("static const SpeakEmbedFile kSpeakEmbedFiles[] = {")
for uri, ident, mime in rows:
    lines.append(f'    {{ "{uri}", {ident}_start, {ident}_end, "{mime}" }},')
lines.append("};")
lines.append(f"static const size_t kSpeakEmbedFileCount = {len(rows)};")
lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"Wrote {OUT} ({len(rows)} files)")
